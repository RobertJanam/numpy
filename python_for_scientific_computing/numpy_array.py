import numpy as np

arr = np.array([1, 2, 3]) # create one dimensional array from the list

print(arr)

arr1 = np.array([[1, 2, 3], [4, 5, 6]]) # create two dimensional array from a nested list 

print(arr1)

arr2 = np.array((1, 2, 3)) # create one dimensional array from a tuple
print(arr2)